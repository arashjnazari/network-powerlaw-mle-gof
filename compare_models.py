"""Compare four discrete probability models on a common degree tail.

Inputs: degree counts and power-law fit summaries generated by main.py.

Models (each normalized over integer k >= xmin):
- Power law: k^(-alpha) / zeta(alpha, xmin)
- Exponential: (1-q) * q^(k-xmin), 0 < q < 1
- Binned lognormal: P(k-.5 <= X < k+.5 | X >= xmin-.5), X lognormal.
- Poisson: P(X=k | X>=xmin), X Poisson; lambda fitted on this same tail.

Comparisons use log-likelihood and AIC on the same tail, with
xmin fixed to the power-law cutoff selected by main.py. They do not
constitute calibrated pairwise hypothesis tests or goodness-of-fit p-values.

The product likelihood treats degrees as independent observations. Network
degrees are dependent, so these AIC scores are exploratory comparisons of
marginal tail shapes, not calibrated tests of competing graph generators.
"""
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.optimize import minimize, minimize_scalar
from scipy.special import log_ndtr, zeta
from scipy.stats import poisson

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "output"


def powerlaw_logpmf(values, xmin, alpha):
    return -alpha * np.log(values) - np.log(zeta(alpha, xmin))


def exponential_fit(values, xmin):
    """Exact MLE for the geometric (discrete-exponential) tail."""
    y = values - xmin
    mean_y = float(np.mean(y))
    q = mean_y / (1.0 + mean_y)
    if not (0.0 < q < 1.0):
        raise ValueError("Exponential fit requires at least one degree above xmin.")
    logp = np.log1p(-q) + y * np.log(q)
    return {"q": q, "log_likelihood": float(np.sum(logp))}


def poisson_logpmf(values: np.ndarray, xmin: int,
                   lambda_poisson: float) -> np.ndarray:
    """Log PMF of a Poisson conditioned on K >= xmin (not a shifted Poisson).

    SciPy's sf(t) is P(K > t), so sf(xmin - 1) is P(K >= xmin).
    Reference: https://docs.scipy.org/doc/scipy/reference/generated/scipy.stats.poisson.html
    """
    log_normalizer = poisson.logsf(xmin - 1, lambda_poisson)
    return poisson.logpmf(values, lambda_poisson) - log_normalizer


def poisson_fit(values: np.ndarray, xmin: int) -> dict:
    """Numerical MLE for the lower-truncated Poisson on the same tail.

    The conditional likelihood accounts for lower truncation. Its fitted
    rate is positive and smaller than the observed tail mean for xmin >= 1.
    """
    values = np.asarray(values)
    if (values.ndim != 1 or values.size == 0 or xmin < 1
            or int(xmin) != xmin or not np.all(np.isfinite(values))
            or np.any(values != np.floor(values)) or np.any(values < xmin)):
        raise ValueError("Poisson fit requires an integer tail with values >= xmin >= 1.")
    if not np.any(values > xmin):
        raise ValueError("Poisson fit requires at least one degree above xmin.")

    unique, counts = np.unique(values, return_counts=True)
    tail_mean = float(np.mean(values))
    upper = float(np.log(tail_mean))
    bounds = (upper - 16.0, upper)

    def nll(log_lambda):
        logs = poisson_logpmf(unique, xmin, float(np.exp(log_lambda)))
        if not np.all(np.isfinite(logs)):
            return np.inf
        return -float(np.dot(counts, logs))

    result = minimize_scalar(nll, method="bounded", bounds=bounds,
                             options={"xatol": 1e-10})
    if not result.success or not np.isfinite(result.fun):
        raise RuntimeError("Poisson MLE did not converge.")
    if np.isclose(result.x, bounds[0], atol=1e-5, rtol=0):
        raise RuntimeError("Poisson MLE reached its lower numerical bound; inspect the data.")
    return {"lambda_poisson": float(np.exp(result.x)),
            "log_likelihood": -float(result.fun)}


def logdiffexp(a, b):
    """Stable log(exp(a) - exp(b)) for a > b."""
    if np.any(b >= a):
        return None
    return a + np.log(-np.expm1(b - a))


def binned_lognormal_logpmf(values, xmin, mu, sigma):
    """Properly normalized integer probabilities via lognormal bin integrals."""
    # SF(x) = Phi(-(ln(x)-mu)/sigma) = ndtr((mu-ln(x))/sigma)
    lower_log_sf = log_ndtr((mu - np.log(values - 0.5)) / sigma)
    upper_log_sf = log_ndtr((mu - np.log(values + 0.5)) / sigma)
    log_mass = logdiffexp(lower_log_sf, upper_log_sf)
    if log_mass is None:
        return None
    log_normalizer = log_ndtr((mu - np.log(xmin - 0.5)) / sigma)
    return log_mass - log_normalizer


def lognormal_fit(values, xmin):
    """MLE using multiple starting points; sigma constrained away from zero."""
    unique, counts = np.unique(values, return_counts=True)
    log_vals = np.log(values)
    center = float(np.mean(log_vals))
    spread = float(max(0.2, np.std(log_vals)))
    bounds = [(np.log(xmin) - 15.0, np.log(np.max(values)) + 10.0),
              (np.log(0.08), np.log(25.0))]

    def nll(params):
        mu, log_sigma = params
        logs = binned_lognormal_logpmf(unique, xmin, mu, np.exp(log_sigma))
        if logs is None or np.any(~np.isfinite(logs)):
            return 1e100
        return -float(np.dot(counts, logs))

    guesses = [(center, np.log(spread)),
               (np.log(xmin), np.log(1.0)),
               (np.log(xmin) - 2.0, np.log(1.5)),
               (np.log(xmin) - 5.0, np.log(2.5))]
    results = [minimize(nll, x0=g, method="L-BFGS-B", bounds=bounds)
               for g in guesses]
    best = min(results, key=lambda r: r.fun)
    if not best.success or not np.isfinite(best.fun):
        raise RuntimeError("Lognormal MLE did not converge.")
    mu, log_sigma = best.x
    return {"mu": float(mu), "sigma": float(np.exp(log_sigma)),
            "log_likelihood": -float(best.fun),
            "near_boundary": bool(np.isclose(best.x[0], bounds[0][0], atol=1e-2) or
                                  np.isclose(best.x[1], bounds[1][1], atol=1e-2))}


def model_ccdf(ks, xmin, model, params):
    if model == "Power law":
        return zeta(params["alpha"], ks) / zeta(params["alpha"], xmin)
    if model == "Exponential":
        return params["q"] ** (ks - xmin)
    if model == "Lognormal":
        mu, sigma = params["mu"], params["sigma"]
        logsf_ks = log_ndtr((mu - np.log(ks - 0.5)) / sigma)
        logsf_xmin = log_ndtr((mu - np.log(xmin - 0.5)) / sigma)
        return np.exp(logsf_ks - logsf_xmin)
    if model == "Poisson":
        lambda_poisson = params["lambda_poisson"]
        logsf_ks = poisson.logsf(np.asarray(ks) - 1, lambda_poisson)
        logsf_xmin = poisson.logsf(xmin - 1, lambda_poisson)
        return np.exp(logsf_ks - logsf_xmin)
    raise ValueError(f"Unknown model: {model}")


def analyze(network, summary_row):
    path = OUT / f"{network.lower()}_degrees.csv"
    degrees_table = pd.read_csv(path)
    # Recover exact integer sample without regenerating any random graph.
    degrees = np.repeat(degrees_table["degree"].to_numpy(dtype=int),
                        degrees_table["count"].to_numpy(dtype=int))
    xmin = int(summary_row["xmin"])
    tail = degrees[degrees >= xmin]
    alpha = float(summary_row["alpha_mle"])
    n = len(tail)
    if n != int(summary_row["n_tail"]):
        raise ValueError(f"{network}: degree data and summary.csv disagree on n_tail.")
    if len(degrees) != int(summary_row["nodes"]):
        raise ValueError(f"{network}: degree data and summary.csv disagree on node count.")

    power = {"alpha": alpha,
             "log_likelihood": float(np.sum(powerlaw_logpmf(tail, xmin, alpha)))}
    exponential = exponential_fit(tail, xmin)
    lognormal = lognormal_fit(tail, xmin)
    poisson_model = poisson_fit(tail, xmin)
    models = {"Power law": (power, 1),
              "Exponential": (exponential, 1),
              "Lognormal": (lognormal, 2),
              "Poisson": (poisson_model, 1)}
    rows = []
    for name, (params, num_parameters) in models.items():
        ll = params["log_likelihood"]
        aic = 2 * num_parameters - 2 * ll
        rows.append({"network": network, "model": name, "xmin": xmin,
                     "n_tail": n, "n_parameters": num_parameters,
                     "log_likelihood": ll, "AIC": aic,
                     "alpha": params.get("alpha", np.nan),
                     "q": params.get("q", np.nan),
                     "mu": params.get("mu", np.nan),
                     "sigma": params.get("sigma", np.nan),
                     "lognormal_near_boundary": params.get("near_boundary", False),
                     "lambda_poisson": params.get("lambda_poisson", np.nan)})
    result = pd.DataFrame(rows)
    result["delta_AIC"] = result["AIC"] - result["AIC"].min()

    k = np.arange(xmin, int(tail.max()) + 1)
    sorted_tail = np.sort(tail)
    empirical_ccdf = (n - np.searchsorted(sorted_tail, k, side="left")) / n
    fig, ax = plt.subplots(figsize=(7.8, 5.5))
    ax.loglog(k, empirical_ccdf, "o", ms=4, label="Empirical tail")
    for name, (params, _) in models.items():
        ax.loglog(k, model_ccdf(k, xmin, name, params), "-", lw=1.8,
                  label=f"{name} (AIC={result.loc[result.model == name, 'AIC'].iloc[0]:.1f})")
    ax.set(xlabel="Degree k", ylabel="P(K >= k | K >= xmin)",
           title=f"{network}: competing fits on same tail (xmin={xmin}, n={n})")
    # Display CCDF values down to half the empirical single-observation level.
    # Axis limits do not affect model fitting or likelihood calculations.
    ax.set_ylim(0.5 / n, 1.2)
    ax.legend()
    ax.grid(alpha=0.25)
    fig.tight_layout()
    fig.savefig(OUT / f"{network.lower()}_model_comparison.png", dpi=180)
    plt.close(fig)
    return result


def main():
    summary = OUT / "summary.csv"
    if not summary.exists() or any(not (OUT / f"{n}_degrees.csv").exists()
                                   for n in ("ba", "er")):
        raise FileNotFoundError("Run main.py first to generate output/summary.csv "
                                "and output/ba_degrees.csv, er_degrees.csv.")
    table = pd.read_csv(summary)
    results = []
    for name in ("BA", "ER"):
        s = table.loc[table.network == name]
        if len(s) != 1:
            raise ValueError(f"Expected exactly one {name} row in summary.csv")
        results.append(analyze(name, s.iloc[0]))
    combined = pd.concat(results, ignore_index=True)
    combined.to_csv(OUT / "model_comparison.csv", index=False)
    for name in ("BA", "ER"):
        subset = combined.loc[combined.network == name]
        print(f"\n{name}: same sample for all models (xmin={int(subset.iloc[0].xmin)}, n={int(subset.iloc[0].n_tail)})")
        print(subset[["model", "log_likelihood", "AIC", "delta_AIC"]].to_string(
            index=False, float_format=lambda x: f"{x:.3f}"))
        winner = subset.loc[subset.AIC.idxmin(), "model"]
        print(f"Lowest AIC: {winner} (relative ranking, not an absolute-fit test)")
    print(f"\nSaved: {OUT / 'model_comparison.csv'} and BA/ER model comparison PNGs")
    print("Lognormal model: binned continuous lognormal on integer degrees.")
    print("Models are compared only on the power-law-selected tail; AIC is not a GOF test.")
    print("Poisson is conditioned on K >= xmin, with lambda fitted to that tail.")
    print("Plots show CCDF >= 0.5/n_tail; smaller model probabilities are outside the axes.")
    print("AIC scores are exploratory because network degrees are dependent.")


if __name__ == "__main__":
    main()
